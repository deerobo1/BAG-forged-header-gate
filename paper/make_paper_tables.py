"""Build the gate paper's results tables from sprint3/results/*.csv.

    python paper/make_paper_tables.py

Writes paper/tables/g_*.tex. Every number printed in a table comes from one CSV through the
function named in the table's comment line; paper/check_ledger.py recomputes them independently.
"""

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "sprint3" / "results"
OUT = ROOT / "paper" / "tables"

RUNS = ["5gad2022", "mcfp", "mcfp_strict", "ciciot2022", "tii_ssrc23", "iot23", "ustc"]
NAME = {"5gad2022": "5GAD-2022", "mcfp": "MCFP", "mcfp_strict": "MCFP strict", "ciciot2022": "CICIoT2022",
        "tii_ssrc23": "TII-SSRC-23", "iot23": "IoT-23", "ustc": "USTC-TFC2016"}
SHORT = {"5GAD": "5gad2022", "MCFP": "mcfp", "MCFP strict": "mcfp_strict", "CICIoT": "ciciot2022",
         "TII": "tii_ssrc23", "IoT-23": "iot23", "USTC": "ustc"}


def f1(v):
    return f"{v:.1f}"


def f2(v):
    return f"{v:.2f}"


def write(name, comment, colspec, header, rows):
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    text = (f"% {comment}\n% generated by paper/make_paper_tables.py from sprint3/results\n"
            f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n")
    (OUT / f"{name}.tex").write_text(text, encoding="utf-8")


def n1_rows():
    """Undefended detectors: worst header attack (a, b, m), conditional %."""
    d = pd.read_csv(RES / "summary_n1.csv")
    d["run"] = d["Run"].map(SHORT)
    d = d.set_index("run").loc[RUNS]
    return [[NAME[r], f1(x["F worst header, mean"]), f1(x["F sd"]), f1(x["F min seed"]), f1(x["F time"]),
             f1(x["XGBoost worst header, mean"]), f1(x["XGBoost sd"]), f1(x["XGBoost min seed"]), f1(x["XGBoost time"])]
            for r, x in d.iterrows()]


def gateC_header():
    """3-seed mean of gate F+B+C_A's worst unconditional header success, random split."""
    e4 = pd.read_csv(RES / "e4_methods.csv")
    r = e4[(e4.split == "random") & (e4.method == "gate+C_A")]
    return r.groupby("run").header_uncond_max.mean()


def n2_rows():
    """Clean macro-F1 (3-seed mean), worst unconditional header success, Benign recall, N2 pass."""
    d = pd.read_csv(RES / "summary_n2.csv")
    d = d[d.setting == "mean"].set_index("run").loc[RUNS]
    hc = gateC_header()
    rows = []
    for r, x in d.iterrows():
        rows.append([NAME[r], f1(x.F), f1(x.B), f1(x.gate), f1(x["gate+C"]),
                     f2(x.hdr_B), f2(x.hdr_gate), f2(hc[r]),
                     f1(x.benign_recall_F), f1(x.benign_recall_gate), "yes" if str(x["pass"]) == "True" else "no"])
    return rows


def b_bound():
    """Per cell of e2_bound.csv: each gate's unconditional success next to B's own miss rate in the same
    setting and attack (the guaranteed bound, which names B only)."""
    d = pd.read_csv(RES / "e2_bound.csv")
    key = ["run", "split", "seed", "attack"]
    b = d[d.gate == "B"][key + ["uncond_pct"]].rename(columns={"uncond_pct": "b_miss"})
    return d[d.gate != "B"].merge(b, on=key, how="left")


def bound_rows():
    """E2 bound check over all 28 settings (random seeds 0-2 and time, 7 runs), against B's miss rate."""
    d = b_bound()
    label = {"gate": "F+B", "gate+C_A": "F+B+C", "xgb_gate": "XGBoost+B", "adv8_gate": "adv.\\ training+B"}
    rows = []
    for g in ["gate", "gate+C_A", "xgb_gate", "adv8_gate"]:
        for a, x in d[d.gate == g].groupby("attack"):
            viol = int((x.uncond_pct > x.b_miss + 1e-9).sum())
            rows.append([label[g], f"({a})", str(len(x)), str(viol), f2(x.uncond_pct.max()), f2(x.b_miss.max())])
    return rows


def realize_rows():
    """E5: forged packets checked by three validators; live sessions."""
    f = pd.read_csv(RES / "e5_forge.csv").set_index("run")
    l = pd.read_csv(RES / "e5_live.csv").set_index("run")
    err = ["own_malformed", "own_ip_csum", "own_tcp_csum", "dpkt_malformed", "dpkt_ip_csum", "dpkt_tcp_csum",
           "scapy_malformed", "scapy_ip_csum", "scapy_tcp_csum"]
    rows = []
    for r in [x for x in RUNS if x in f.index]:
        rows.append([NAME[r], str(int(f.loc[r, "forged_flows"])), f"{int(f.loc[r, 'forged_packets']):,}".replace(",", "{,}"),
                     str(int(f.loc[r, err].sum())), str(int(l.loc[r, "sessions"])), str(int(l.loc[r, "handshake_ok"])),
                     str(int(l.loc[r, "echo_ok"]))])
    return rows


def packet_rows():
    """E6: gate F+B+C_A, held-out packet attacks, conditional %, 3-seed mean, random split."""
    d = pd.read_csv(RES / "summary_e6_packets_C_A.csv")
    m = d[d.split == "random"].groupby("run").mean(numeric_only=True).loc[RUNS]
    rows = []
    for r, x in m.iterrows():
        ok = x.held_worst < 10 and x.recall_drop <= 1
        rows.append([NAME[r], f1(x.held_d), f1(x.held_f), f1(x.held_u), f1(x.held_L), f1(x.held_La),
                     f1(x.held_H), f1(x.held_Ha), f1(x.held_worst), f2(x.recall_drop), "yes" if ok else "no"])
    return rows


def group_rows():
    """E8: XGBoost gate' (F'+B') on the benign-host-disjoint split vs the random split."""
    d = pd.read_csv(RES / "summary_e8_group.csv")
    rows = []
    for r in RUNS:
        g = d[(d.run == r) & (d.split == "group")].set_index("method")
        a = d[(d.run == r) & (d.split == "random")].set_index("method")
        rows.append([NAME[r], f1(g.loc["gate'", "benign_recall"]), f1(g.loc["gate'", "benign_recall_min"]),
                     f1(a.loc["gate'", "benign_recall"]), f1(g.loc["F'", "benign_recall"]), f1(g.loc["B'", "benign_recall"]),
                     f1(g.loc["gate'", "clean_f1"]), f1(a.loc["gate'", "clean_f1"]),
                     f2(g.loc["gate'", "header_uncond"]), f1(g.loc["F'", "header_uncond"])])
    return rows


def cost_rows():
    """E9b: parameters, multiply-adds and CPU latency, 5GAD seed 0, 12 threads."""
    d = pd.read_csv(RES / "e9_cost.csv")
    rows = []
    for m in ["F", "F+B", "F+B+C"]:
        b1 = d[(d.method == m) & (d.batch == 1)].iloc[0]
        b256 = d[(d.method == m) & (d.batch == 256)].iloc[0]
        trees = r"$^\dagger$" if b1.c_trees else ""  # C's tree count goes in the caption
        rows.append([m, f"{b1.params / 1e6:.2f}\\,M{trees}", f"{b1.macs / 1e6:.1f}\\,M",
                     f"{b1.ms_per_flow:.1f} ({b1.latency_ratio:.2f}$\\times$)", f"{b256.ms_per_flow:.2f} ({b256.latency_ratio:.2f}$\\times$)"])
    return rows


def main():
    OUT.mkdir(exist_ok=True)
    write("g_n1", "n1_rows: summary_n1.csv", "lrrrrrrrr",
          r"& \multicolumn{4}{c}{MobileNetV2 F} & \multicolumn{4}{c}{XGBoost} \\ \cmidrule(lr){2-5}\cmidrule(lr){6-9}"
          "\nRun & Mean & SD & Min & Time & Mean & SD & Min & Time", n1_rows())
    write("g_n2", "n2_rows: summary_n2.csv (setting=mean), e4_methods.csv (gate+C_A header)", "lrrrrrrrrrc",
          r"& \multicolumn{4}{c}{Clean macro-F1} & \multicolumn{3}{c}{Header attack, uncond.\ \%} & \multicolumn{2}{c}{Benign rec.} & \\"
          r" \cmidrule(lr){2-5}\cmidrule(lr){6-8}\cmidrule(lr){9-10}"
          "\nRun & F & B & F+B & F+B+C & B & F+B & F+B+C & F & F+B & Pass", n2_rows())
    write("g_bound", "bound_rows: e2_bound.csv (B rows give the bound)", "llrrrr",
          r"Gate & Attack & Cells & Viol. & Max success & Max B miss", bound_rows())
    write("g_realize", "realize_rows: e5_forge.csv, e5_live.csv", "lrrrrrr",
          r"& \multicolumn{3}{c}{Forged (R1)} & \multicolumn{3}{c}{Live sessions (R2, R3)} \\ \cmidrule(lr){2-4}\cmidrule(lr){5-7}"
          "\nRun & Flows & Packets & Errors & Sessions & Handshake & Echo", realize_rows())
    write("g_packets", "packet_rows: summary_e6_packets_C_A.csv (random split, mean of seeds 0-2)", "lrrrrrrrrrc",
          r"Run & (d) & (f) & (u) & (L) & (La) & (H) & (Ha) & Worst & Rec. & Pass", packet_rows())
    write("g_group", "group_rows: summary_e8_group.csv", "lrrrrrrrrr",
          r"& \multicolumn{5}{c}{Benign recall \%} & \multicolumn{2}{c}{Macro-F1} & \multicolumn{2}{c}{Header, uncond.\ \%} \\"
          r" \cmidrule(lr){2-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}"
          "\nRun & Gate$'$ & Min seed & Random & F$'$ & B$'$ & Group & Random & Gate$'$ & F$'$", group_rows())
    write("g_cost", "cost_rows: e9_cost.csv", "lrrrr",
          r"Model & Params & MACs & ms, batch 1 & ms, batch 256", cost_rows())
    print("wrote", sorted(p.name for p in OUT.glob("g_*.tex")))


if __name__ == "__main__":
    main()
