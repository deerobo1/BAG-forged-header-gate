"""Scores sprint 3's results against sprint3/PREREG.md and writes the summary tables (CSV and LaTeX).

  python sprint3/code/report3.py    -> sprint3/results/summary_*.csv, sprint3/tables/*.tex, and prints every verdict
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd

import s3

R = s3.RESULTS
TAB = R.parent / "tables"
RUNS = s3.RUNS
NAMES = {"5gad2022": "5GAD", "mcfp": "MCFP", "mcfp_strict": "MCFP strict", "ciciot2022": "CICIoT", "tii_ssrc23": "TII",
         "iot23": "IoT-23", "ustc": "USTC"}
pd.set_option("display.width", 250)


def load(name):
    p = R / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else None


def tex(df, name, caption):
    TAB.mkdir(parents=True, exist_ok=True)
    body = df.to_latex(index=False, float_format=lambda x: f"{x:.1f}", na_rep="--", escape=True)
    (TAB / f"{name}.tex").write_text(f"% {caption}\n% generated by sprint3/code/report3.py\n" + body)


def ms(x):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    return (x.mean(), x.std(ddof=1) if len(x) > 1 else float("nan"), len(x)) if len(x) else (np.nan, np.nan, 0)


def e1_e2():
    e1, e2 = load("e1_invariance"), load("e2_bound")
    out = {"e1_cells": len(e1), "e1_fail": int((~e1["pass"]).sum()), "e1_flows_compared": int(e1["flows_changed"].sum()),
           "e1_max_b_logit_gap_m": float(e1["b_logit_max_gap_m"].max()),
           "e2_cells": len(e2), "e2_violations": int(e2["violation"].sum())}
    print("E1/E2", out)
    t = e2.groupby(["gate", "attack"]).agg(cells=("violation", "size"), violations=("violation", "sum"),
                                           max_uncond=("uncond_pct", "max"), max_bound=("bound_uncond_pct", "max")).reset_index()
    t.to_csv(R / "summary_e2.csv", index=False)
    print(t.to_string())
    return out


def n1():
    """Header-attack success of the undefended detectors (F = MobileNetV2 stand-in, XGBoost), per run and setting."""
    d = load("e4_methods")
    rows = []
    for run in RUNS:
        r = {"Run": NAMES[run]}
        for meth, col in (("F", "F"), ("xgb", "XGBoost")):
            x = d[(d.run == run) & (d.method == meth)]
            rnd = x[x.split == "random"]
            vals = rnd[["cond_a", "cond_b", "cond_m"]].max(axis=1, skipna=True)
            m, sd, n = ms(vals)
            r[f"{col} worst header, mean"] = m
            r[f"{col} sd"] = sd
            r[f"{col} min seed"] = vals.min()
            t = x[x.split == "time"][["cond_a", "cond_b", "cond_m"]].max(axis=1, skipna=True)
            r[f"{col} time"] = float(t.iloc[0]) if len(t) else np.nan
        rows.append(r)
    t = pd.DataFrame(rows)
    t.to_csv(R / "summary_n1.csv", index=False)
    tex(t, "n1_header_attacks", "Worst header attack (a, b, m), conditional success %, undefended detectors")
    print(t.to_string())
    return t


def n2():
    """The brief's N2 pass mark, per run, on the 3-seed mean, each seed and the time split."""
    d, b = load("e4_methods"), load("e4_boot")
    rows = []
    for (split, seed) in [("mean", None)] + s3.SETTINGS:
        for run in RUNS:
            x = d[d.run == run] if split == "mean" else d[(d.run == run) & (d.split == split) & (d.seed == seed)]
            if split == "mean":
                x = x[x.split == "random"]
            if x.empty:
                continue
            g = lambda m, c: x[x.method == m][c].mean()
            f1F, f1B, f1G, f1GC = g("F", "clean_f1"), g("B", "clean_f1"), g("gate", "clean_f1"), g("gate+C_A", "clean_f1")
            hB, hG = g("B", "header_uncond_max"), g("gate", "header_uncond_max")
            ok = (f1G >= f1F - 2) and (f1G >= f1B + 2) and (hG <= hB + 1e-9)
            rows.append({"setting": split if split == "mean" else f"{split}{seed}", "run": run, "F": f1F, "B": f1B, "gate": f1G,
                         "gate+C": f1GC, "gate-F": f1G - f1F, "gate-B": f1G - f1B, "hdr_B": hB, "hdr_gate": hG,
                         "c1_within2_of_F": f1G >= f1F - 2, "c2_beats_B_by2": f1G >= f1B + 2, "c3_hdr_le_B": hG <= hB + 1e-9, "pass": ok,
                         "benign_recall_F": g("F", "benign_recall"), "benign_recall_gate": g("gate", "benign_recall"),
                         "benign_recall_gateC": g("gate+C_A", "benign_recall")})
    t = pd.DataFrame(rows)
    # Holm across the 7 runs, per random seed, for gate > B and gate > F - 2
    hb = []
    for (split, seed), grp in b[b.method == "gate"].groupby(["split", "seed"]):
        for vs in ("B", "F"):
            g2 = grp[grp.vs == vs].set_index("run").reindex(RUNS)
            adj = s3.holm(g2["p_one_sided"].fillna(1).to_numpy())
            for run, p, a, lo, hi, diff in zip(RUNS, g2["p_one_sided"], adj, g2["lo"], g2["hi"], g2["diff"]):
                hb.append({"split": split, "seed": seed, "run": run, "vs": vs, "diff": diff, "lo": lo, "hi": hi, "p": p, "p_holm": a,
                           "significant_0.05": a < 0.05})
    hb = pd.DataFrame(hb)
    hb.to_csv(R / "summary_n2_holm.csv", index=False)
    t.to_csv(R / "summary_n2.csv", index=False)
    passes = t.groupby("setting")["pass"].sum()
    print(t.round(2).to_string())
    print("N2 passes per setting (of 7):", passes.to_dict())
    show = t[t.setting == "mean"][["run", "F", "B", "gate", "gate+C", "hdr_B", "hdr_gate", "pass"]].copy()
    show["run"] = show["run"].map(NAMES)
    tex(show, "n2_masking_vs_gate", "Clean macro-F1 (3-seed mean) and worst unconditional header-attack success %")
    return t, hb


def e3():
    d = load("e3_flags")
    if d is None:
        return None
    e2 = load("e2_bound")
    rows = []
    for (split, seed, run), g in d[d["mode"] == "best8"].groupby(["split", "seed", "run"]):
        bound = e2[(e2.run == run) & (e2.split == split) & (e2.seed == seed) & (e2.gate == "gate+C_A") & (e2.attack == "m")]
        u = float(bound["bound_uncond_pct"].iloc[0]) if len(bound) else np.nan
        get = lambda a, m: float(g[(g.attack == a) & (g.method == m)]["uncond"].iloc[0])
        rows.append({"run": run, "split": split, "seed": seed, "C_f1": get("f1", "C"), "B_f1": get("f1", "B"),
                     "gateC_f1": get("f1", "gate+C"), "gate_f1m": get("f1m", "gate"), "gateC_f1m": get("f1m", "gate+C"),
                     "gateC_bound_m": u, "excess_over_bound": get("f1m", "gate+C") - u})
    t = pd.DataFrame(rows)
    t.to_csv(R / "summary_e3.csv", index=False)
    print(t.round(2).to_string())
    print("E3: settings where flags+M exceed the M bound by > 1 point:", int((t.excess_over_bound > 1).sum()), "of", len(t))
    return t


def e6(name="e6_packets", variant="C_A"):
    d = load(name)
    if d is None:
        return None
    d = d[d.C_variant == variant]
    rows = []
    for (split, seed, run), g in d.groupby(["split", "seed", "run"]):
        gc = g[g.method == "gate+C"]
        held = gc[gc.family.str.startswith("held-out")]
        seen = gc[gc.family == "seen"]
        worst_attack = held.loc[held["cond"].idxmax(), "attack"] if len(held) else None
        rows.append({"run": run, "split": split, "seed": seed, "held_worst": held["cond"].max(), "held_worst_attack": worst_attack,
                     "seen_worst": seen["cond"].max(),
                     **{f"held_{a}": float(held[held.attack == a]["cond"].iloc[0]) for a in held.attack},
                     "mixed_g64": float(gc[gc.attack == "g64"]["cond"].iloc[0]) if (gc.attack == "g64").any() else np.nan,
                     "recall_drop": float(g["benign_recall_gate"].iloc[0] - g["benign_recall_gateC"].iloc[0]),
                     "f1_gateC_minus_gate": float(g["clean_f1_gateC"].iloc[0] - g["clean_f1_gate"].iloc[0])})
    t = pd.DataFrame(rows)
    t.to_csv(R / f"summary_{name}_{variant}.csv", index=False)
    mean = t[t.split == "random"].groupby("run")[["held_worst", "recall_drop"]].mean()
    mean["pass"] = (mean.held_worst < 10) & (mean.recall_drop <= 1)
    print(t.round(2).to_string())
    print(mean.round(2).to_string())
    print(f"{name}/{variant}: runs passing on the 3-seed mean: {int(mean['pass'].sum())} of {len(mean)}")
    return t, mean


def e8():
    """Group (benign-host-disjoint) versus random split, XGBoost-family members, 3 seeds."""
    d = load("e8_group")
    if d is None:
        return None
    d["benign_test_share"] = 100 * d["benign_test"] / d["n_test"]
    d["header_uncond"] = d[["uncond_a", "uncond_b", "uncond_m"]].max(axis=1)
    agg = d.groupby(["run", "split", "method"]).agg(seeds=("seed", "nunique"), clean_f1=("clean_f1", "mean"),
                                                     clean_f1_sd=("clean_f1", "std"), benign_recall=("benign_recall", "mean"),
                                                     benign_recall_min=("benign_recall", "min"), header_uncond=("header_uncond", "max"),
                                                     cond_g=("cond_g", "mean"), benign_test_share=("benign_test_share", "mean")).reset_index()
    agg.to_csv(R / "summary_e8_group.csv", index=False)
    show = agg[agg.method.isin(["F'", "B'", "gate'", "gate'+C_A"])].pivot_table(
        index=["run", "method"], columns="split", values=["clean_f1", "benign_recall", "header_uncond"]).round(2)
    print(show.to_string())
    return agg


