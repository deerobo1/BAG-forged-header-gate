def tables():
    """Ready-to-paste LaTeX for E2, E5, E6, E7, E8 (N1, N2 are written by n1(), n2())."""
    e2 = pd.read_csv(R / "summary_e2.csv")
    tex(e2.rename(columns={"gate": "Gate", "attack": "Attack", "cells": "Cells", "violations": "Violations",
                           "max_uncond": "Max success %", "max_bound": "Max bound %"}), "e2_bound", "Bound check, all settings")
    f = pd.read_csv(R / "e5_forge.csv")[["run", "forged_flows", "forged_packets", "own_malformed", "own_ip_csum", "own_tcp_csum",
                                          "dpkt_malformed", "dpkt_tcp_csum", "scapy_malformed", "scapy_tcp_csum"]]
    lv = pd.read_csv(R / "e5_live.csv")[["run", "sessions", "handshake_ok", "echo_ok", "syn_values_on_wire"]]
    t = f.merge(lv, on="run")
    t["run"] = t["run"].map(NAMES)
    tex(t, "e5_realizability", "Forged packets: validator errors and live sessions")
    for name, v, out in (("e6_packets", "C_A", "e6_length_view"), ("e7_cfull", "C_full", "e7_fix1"), ("e7_cfull", "C_fix2", "e7_fix2")):
        s = pd.read_csv(R / f"summary_{name}_{v}.csv")
        cols = [c for c in ("held_worst", "held_d", "held_f", "held_u", "held_s24", "held_a4", "held_L", "held_La", "held_H", "held_Ha",
                            "recall_drop") if c in s]
        m = s[s.split == "random"].groupby("run")[cols].mean().reindex(RUNS).reset_index()
        m["run"] = m["run"].map(NAMES)
        tex(m, out, f"Gate F+B+{v}, held-out conditional success %, 3-seed mean")
    g = pd.read_csv(R / "summary_e8_group.csv")
    g = g[g.method == "gate'"].pivot_table(index="run", columns="split", values=["benign_recall", "clean_f1"]).reindex(RUNS)
    g.columns = [f"{a} ({b})" for a, b in g.columns]
    g = g.reset_index()
    g["run"] = g["run"].map(NAMES)
    tex(g, "e8_group", "Gate' (XGBoost F'+B'): benign-host-disjoint vs random split")


